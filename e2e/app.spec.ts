import { expect, test, type Page } from '@playwright/test';
import { parseSubtitle } from '../src/core';

const sample = '1\n00:00:01,000 --> 00:00:03,000\n Hello 世界 😀 \nSecond line\n\n2\n00:00:04,000 --> 00:00:06,000\nHello again\n';
async function importFiles(page: Page, files = [{ name: 'lesson.srt', mimeType: 'text/plain', buffer: Buffer.from(sample) }]) {
  const picker = page.waitForEvent('filechooser');
  await page.getByRole('button', { name: '选择文件', exact: true }).click();
  await (await picker).setFiles(files);
}
