test('replace preview, export actual bytes and persist metadata history', async ({ page }) => {
  await page.goto('/#/tools/replace');
  await importFiles(page);
  await page.getByLabel('查找内容', { exact: true }).fill('Hello');
  await page.getByLabel('替换为', { exact: true }).fill('你好');
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.locator('.task-row .status-badge')).toHaveText('已处理');
  await expect(page.locator('.preview-grid').getByText('你好 again', { exact: true })).toBeVisible();
  await page.locator('.results-panel').screenshot({ path: 'docs/screenshots/replace-preview.png', animations: 'disabled' });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '另存为', exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('lesson_processed.srt');
  const stream = await download.createReadStream(); const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const output = Buffer.concat(chunks).toString('utf8');
  expect(output).toContain('你好 世界 😀'); expect(output).not.toContain('Hello'); expect(output).toContain('00:00:01,000');
  await page.getByRole('link', { name: '处理记录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '查找和替换', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: '查找和替换', exact: true })).toBeVisible();
  const stored = await page.evaluate(() => JSON.stringify(localStorage));
  expect(stored).not.toContain('世界');
});
test('batch isolates errors, validates params and exports a collision-free ZIP', async ({ page }) => {
  await page.goto('/#/batch');
  await importFiles(page, [{ name: 'same.srt', mimeType: 'text/plain', buffer: Buffer.from(sample) }, { name: 'same.srt', mimeType: 'text/plain', buffer: Buffer.from(sample) }, { name: 'bad.srt', mimeType: 'text/plain', buffer: Buffer.from('not a subtitle') }]);
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.getByText('请输入要查找的内容。')).toBeVisible();
  await page.getByLabel('查找内容', { exact: true }).fill('Hello');
  await page.getByLabel('替换为', { exact: true }).fill('Hi');
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.locator('.task-row .status-badge.success')).toHaveCount(2);
  await expect(page.locator('.task-row .status-badge.failed')).toHaveCount(1);
  await expect(page.locator('.output-list')).toContainText('same_processed.srt');
  await expect(page.locator('.output-list')).toContainText('same_processed (2).srt');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 ZIP', exact: true }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('subtitle-tools_results.zip');
  const stream = await download.createReadStream(); const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const { default: JSZip } = await import('jszip'); const zip = await JSZip.loadAsync(Buffer.concat(chunks));
  expect(Object.keys(zip.files)).toEqual(['same_processed.srt', 'same_processed (2).srt']);
});
test('browser drop, merge, invalid time rejection and explicit repair', async ({ page }) => {
  await page.goto('/#/tools/merge');
  await page.locator('.dropzone').evaluate((element, content) => { const transfer = new DataTransfer(); transfer.items.add(new File([content], 'first.srt', { type: 'text/plain' })); transfer.items.add(new File([content], 'second.srt', { type: 'text/plain' })); element.dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: transfer })); }, sample);
  await expect(page.locator('.file-row')).toHaveCount(2);
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.locator('.task-row .status-badge.success')).toHaveCount(1);
  await expect(page.locator('.document-meta')).toContainText('输出 4 条字幕');
  await page.getByRole('button', { name: '清空', exact: true }).click();
  await page.goto('/#/tools/shift');
  await importFiles(page);
  await page.getByLabel('偏移量（毫秒）').fill('-2000');
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.locator('.task-row .status-badge.failed')).toHaveCount(1);
  await expect(page.getByRole('button', { name: '另存为', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '清空', exact: true }).click();
  await page.goto('/#/tools/repair');
  await importFiles(page, [{ name: 'invalid.srt', mimeType: 'text/plain', buffer: Buffer.from('1\n00:00:02,000 --> 00:00:01,000\nHello\n') }]);
  await page.getByLabel('无效时间策略').selectOption('extend');
  await page.getByRole('button', { name: '预览处理结果', exact: true }).click();
  await expect(page.locator('.task-row .status-badge.success')).toHaveCount(1);
  await expect(page.getByRole('button', { name: '另存为', exact: true })).toBeVisible();
});
test('blank template follows the user timing rules and roundtrips as real SRT', async ({ page }) => {
  await page.goto('/#/template');
  await page.getByLabel('条目数量', { exact: true }).fill('3');
  await page.getByLabel('每条显示时长（毫秒）', { exact: true }).fill('1500');
  await page.getByLabel('条目间隔（毫秒）', { exact: true }).fill('250');
  await page.getByRole('button', { name: '生成预览', exact: true }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出模板', exact: true }).click();
  const download = await downloading;
  const stream = await download.createReadStream(); const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const result = parseSubtitle(Buffer.concat(chunks).toString('utf8'), download.suggestedFilename());
  expect(result.diagnostics.filter(d => d.severity === 'error')).toEqual([]);
  expect(result.document.cues.map(c => [c.startMs, c.endMs, c.text])).toEqual([[0, 1500, ''], [1750, 3250, ''], [3500, 5000, '']]);
});
